// optionFingerprint is every exported ROption field, times with their location, the form the
// golden table was written in from rrule-go v1.8.3.
func optionFingerprint(opt *rrule.ROption) string {
	rv := reflect.ValueOf(opt).Elem()
	var b strings.Builder
	for i := 0; i < rv.NumField(); i++ {
		f := rv.Type().Field(i)
		if !f.IsExported() {
			continue
		}
		if t, ok := rv.Field(i).Interface().(time.Time); ok {
			s := "zero"
			if !t.IsZero() {
				s = t.Format(time.RFC3339Nano) + "@" + t.Location().String()
			}
			fmt.Fprintf(&b, "%s=%s;", f.Name, s)
			continue
		}
		fmt.Fprintf(&b, "%s=%v;", f.Name, rv.Field(i).Interface())
	}
	return b.String()
}

// TestParseRuleText_MatchesV183 holds parseRuleText to rrule-go v1.8.3's own parse of 637 rule
// texts (testdata/rrule_v183_parse_golden.json: every DTSTART spelling, UNTIL forms, a fuzz
// sample; generated by v1.8.3 before the library upgrade): the same acceptance, every exported
// field, the stored spelling, and whether the rule builds.
func TestParseRuleText_MatchesV183(t *testing.T) {
	raw, err := os.ReadFile(filepath.Join("testdata", "rrule_v183_parse_golden.json"))
	require.NoError(t, err)
	var rows []struct {
		Text        string `json:"text"`
		OK          bool   `json:"ok"`
		Fields      string `json:"fields"`
		RRuleString string `json:"rrule_string"`
		Builds      bool   `json:"builds"`
	}
	require.NoError(t, json.Unmarshal(raw, &rows))
	require.Len(t, rows, 637)
	for i, row := range rows {
		t.Run(strconv.Itoa(i), func(t *testing.T) {
			opt, err := parseRuleText(row.Text)
			if !row.OK {
				require.Error(t, err, "v1.8.3 refused %q", row.Text)
				return
			}
			require.NoError(t, err, "v1.8.3 accepted %q", row.Text)
			assert.Equal(t, row.Fields, optionFingerprint(opt), "%q", row.Text)
			assert.Equal(t, row.RRuleString, opt.RRuleString(), "%q", row.Text)
			built := *opt
			if built.Dtstart.IsZero() {
				built.Dtstart = time.Date(2026, 1, 1, 9, 0, 0, 0, time.UTC)
			}
			_, buildErr := rrule.NewRRule(built)
			assert.Equal(t, row.Builds, buildErr == nil, "NewRRule on %q: %v", row.Text, buildErr)
		})
	}
}

// TZID=Local reads the value in the process zone, as v1.8.3's time.LoadLocation("Local") did. It
// is kept out of the golden table, whose values must not depend on the zone it is run in.
func TestParseRuleText_TZIDLocal(t *testing.T) {
	opt, err := parseRuleText("DTSTART;TZID=Local:20260301T090000\nRRULE:FREQ=DAILY")
	require.NoError(t, err)
	want := time.Date(2026, 3, 1, 9, 0, 0, 0, time.Local) //nolint:gosmopolitan // TZID=Local means the process zone; that is what is checked
	assert.True(t, want.Equal(opt.Dtstart), "%s vs %s", want, opt.Dtstart)
	assert.Same(t, time.Local, opt.Dtstart.Location(), "the process zone itself, whatever it is named") //nolint:gosmopolitan // as above
}

// Texts v1.8.3 refused that the v1.9.0 parser would accept once the DTSTART is gone, because it
// trims the remainder again and reads only the last UNTIL (found by differential fuzzing):
// parseRuleText refuses them too.
func TestParseRuleText_RefusesWhatV183Refused(t *testing.T) {
	for _, text := range []string{
		"RRULE:RRULE:FREQ=DAILY",
		"DTSTART:20260301T090000Z\nRRULE:RRULE:FREQ=DAILY",
		"DTSTART:20260301T090000Z\n FREQ=DAILY",
		"DTSTART:20260301T090000Z\n RRULE:FREQ=DAILY",
		"FREQ=DAILY ;DTSTART=20260301T090000Z",
		"FREQ=DAILY;COUNT=2 ;DTSTART=20260301T090000Z",
		"DTSTART:20260301T090000Z\nFREQ=DAILY\t;DTSTART=20260301T090000Z",
		"DTSTART=20260301T090000Z; FREQ=DAILY",
		"FREQ=DAILY;UNTIL=2026031;UNTIL=20260311T000000Z",
		"FREQ=DAILY;UNTIL=2020310;UNTIL=20260311T000000Z",
		"FREQ=DAILY;UNTIL=202603_0;UNTIL=20260311T000000Z",
	} {
		_, err := parseRuleText(text)
		assert.Error(t, err, "v1.8.3 refused %q", text)
	}
}

// The library on its own still refuses a mismatched DTSTART/UNTIL pair, so parseRuleText is what
// keeps such a stored rule working. When this fails, the library has relaxed: re-check whether the
// shim is still needed.
func TestParseRuleText_LibraryIsStricter(t *testing.T) {
	const mismatched = "FREQ=DAILY;DTSTART=20260301T090000;UNTIL=20260310T090000Z"
	_, err := rrule.StrToROption(mismatched)
	require.Error(t, err, "rrule-go alone refuses the pair")
	opt, err := parseRuleText(mismatched)
	require.NoError(t, err)
	assert.Equal(t, "FREQ=DAILY;UNTIL=20260310T090000Z", opt.RRuleString())

	_, err = rrule.StrToROption("FREQ=DAILY;UNTIL=20260310T090000Z")
	require.NoError(t, err, "rrule-go accepts the DTSTART-free remainder")
}

// A stored DTSTART still counts where it did under v1.8.3: the structured projection is
// read-only, and a DTSTART-free echo is not the stored rule (normaliseROption compares it).
func TestParseRuleText_StoredDTSTARTStillCounts(t *testing.T) {
	for _, stored := range []string{
		"FREQ=DAILY;DTSTART=20260101T090000Z",
		"DTSTART:20260101T090000Z\nRRULE:FREQ=DAILY",
		"DTSTART;TZID=America/New_York:20260101T090000\nRRULE:FREQ=DAILY",
		"FREQ=DAILY;DTSTART=20260101T090000;UNTIL=20260110T090000Z",
	} {
		r := taskRepeatFromRRule(stored)
		require.NotNil(t, r, stored)
		assert.True(t, r.ReadOnly, "a stored DTSTART keeps the projection read-only: %q", stored)
		canon, err := ValidateRuleText("FREQ=DAILY")
		require.NoError(t, err)
		assert.False(t, isValidatedRuleEcho(stored, canon), "a DTSTART-free echo is not the stored rule: %q", stored)
	}
	a, err := parseRuleText("FREQ=DAILY;DTSTART=20260101T090000Z")
	require.NoError(t, err)
	b, err := parseRuleText("FREQ=DAILY;DTSTART=20260102T090000Z")
	require.NoError(t, err)
	assert.NotEqual(t, normaliseROption(a), normaliseROption(b), "the DTSTART instant is compared")
}

// Every entry path that can keep DTSTART text verbatim (the import gate, a duplicate, a v1 raw
// write) still accepts it and the stored rule still advances on completion.
func TestParseRuleText_VerbatimDTSTARTPaths(t *testing.T) {
	const stored = "FREQ=DAILY;DTSTART=20260301T090000;UNTIL=20260310T090000Z"
	imported := &Task{Repeats: stored}
	require.NoError(t, DropUnimportableRepeat(imported))
	assert.Equal(t, stored, imported.Repeats)
	decision, err := resolveCopiedRepeat(stored)
	require.NoError(t, err)
	assert.Equal(t, stored, decision.Repeats)
	require.NoError(t, validateRRule(stored))
	due := time.Date(2026, 3, 2, 9, 0, 0, 0, time.UTC)
	ans := stepOccurrences(nextOccurrenceInput{Rule: stored, Due: dated(due), Now: due.Add(time.Minute), Zone: time.UTC}, 2)
	assert.Empty(t, ans.Reason)
	assert.Len(t, ans.Occurrences, 2)
	// The length limit applies to the text as sent, DTSTART included, as before.
	long := "FREQ=DAILY;DTSTART=20260301T090000Z;BYHOUR=" + strings.Repeat("1,", 240) + "1"
	assert.Greater(t, len(long), maxRRuleLength)
	assert.Error(t, validateRRule(long))
}

// searchInitialDue recovers a panic in its evaluation stage (a nil option stands in for any).
func TestSearchInitialDueRecoversFromAPanic(t *testing.T) {
	now := time.Date(2026, 10, 29, 12, 0, 0, 0, time.UTC)
	in := nextOccurrenceInput{Rule: "FREQ=DAILY", Now: now, Zone: time.UTC}
	var due time.Time
	var reason noNextReason
	require.NotPanics(t, func() {
		due, reason = searchInitialDue(in, nil, rrule.ROption{}, "FREQ=DAILY", 9, 0)
	})
	assert.True(t, due.IsZero())
	assert.Equal(t, reasonEvaluationFailed, reason)
}

// TestParseSitesUseParseRuleText: outside parseRuleText's own file, no non-test file in pkg
// uses an rrule-go Str* parser (StrToROption, StrToRRule, StrToRRuleSet, StrSliceToRRuleSet...),
// called or as a function value, under any import name.
func TestParseSitesUseParseRuleText(t *testing.T) {
	paths := map[string]bool{"github.com/kentonium3/rrule-go": true, "github.com/teambition/rrule-go": true}
	var offenders []string
	err := filepath.WalkDir("..", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		if d.IsDir() || !strings.HasSuffix(path, ".go") || strings.HasSuffix(path, "_test.go") ||
			filepath.Base(path) == "task_rule_parse.go" {
			return nil
		}
		f, err := parser.ParseFile(token.NewFileSet(), path, nil, parser.SkipObjectResolution)
		if err != nil {
			return err
		}
		names := map[string]bool{}
		for _, imp := range f.Imports {
			p, _ := strconv.Unquote(imp.Path.Value)
			if !paths[p] {
				continue
			}
			switch {
			case imp.Name == nil:
				names["rrule"] = true
			case imp.Name.Name == ".":
				offenders = append(offenders, path+": dot import of "+p)
			default:
				names[imp.Name.Name] = true
			}
		}
		ast.Inspect(f, func(n ast.Node) bool {
			if sel, ok := n.(*ast.SelectorExpr); ok {
				if x, ok := sel.X.(*ast.Ident); ok && names[x.Name] && strings.HasPrefix(sel.Sel.Name, "Str") {
					offenders = append(offenders, path+": "+x.Name+"."+sel.Sel.Name)
				}
			}
			return true
		})
		return nil
	})
	require.NoError(t, err)
	assert.Empty(t, offenders, "parse rule text with parseRuleText")
}
